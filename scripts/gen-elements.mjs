#!/usr/bin/env node
/**
 * Generates src/elements/registry.generated.ts from the React components' TypeScript props:
 * one custom element per exported component (`Button` -> `<co-button>`), each prop classified as
 * string / number / boolean / json / function / event / node (see src/elements/define.ts), plus
 * typed `HTMLElementTagNameMap` entries so Angular, Vue and TS users get autocompletion.
 * Also writes src/elements/manifest.generated.json (tags, attributes, properties, events, slots) for the docs site.
 */
import { writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';
import { components, eventName, kebab, root } from './lib/components-meta.mjs';

/* ---------- registry.generated.ts ---------- */
const pascalTag = (tag) => tag.split('-').map((s) => s[0].toUpperCase() + s.slice(1)).join('');
const lines = [];
lines.push('/* GENERATED by scripts/gen-elements.mjs from the components\' TypeScript props. Do not edit. */');
lines.push('import * as C from \'../index\';');
lines.push('import type { ElementSpec } from \'./define\';');
lines.push('');
lines.push('export const elementSpecs: ElementSpec[] = [');
for (const c of components) {
  const p = Object.entries(c.props).map(([k, v]) => `${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: '${v.kind}'`).join(', ');
  const defaults = Object.entries(c.props)
    .filter(([, v]) => !v.optional && v.kind === 'json' && /\[\]$|^(Readonly)?Array</.test(v.type))
    .map(([k]) => `${k}: []`);
  lines.push(`  { tag: '${c.tag}', component: C.${c.name} as never, props: { ${p} }${defaults.length ? `, defaults: { ${defaults.join(', ')} }` : ''} },`);
}
lines.push('];');
lines.push('');
for (const c of components) {
  const keys = Object.entries(c.props).filter(([, v]) => v.kind !== 'node' && v.kind !== 'event').map(([k]) => JSON.stringify(k));
  const propsTypeName = `ComponentProps<typeof C.${c.name}>`;
  const pick = keys.length ? `Partial<Pick<${propsTypeName}, ${keys.join(' | ')}>>` : '{}';
  lines.push(`/** \`<${c.tag}>\`: the ${c.name} component as a custom element. */`);
  lines.push(`export type ${pascalTag(c.tag)}Element = HTMLElement & ${pick};`);
}
lines.push('');
lines.push('declare global {');
lines.push('  interface HTMLElementTagNameMap {');
for (const c of components) lines.push(`    '${c.tag}': ${pascalTag(c.tag)}Element;`);
lines.push('  }');
lines.push('}');
const header = "import type { ComponentProps } from 'react';\n";
writeFileSync(resolve(root, 'src/elements/registry.generated.ts'), header + lines.join('\n') + '\n');

/* ---------- manifest for docs ---------- */
const manifest = components.map((c) => ({
  component: c.name,
  tag: c.tag,
  aliases: c.aliases,
  attributes: Object.entries(c.props)
    .filter(([, v]) => ['string', 'number', 'boolean', 'json'].includes(v.kind))
    .map(([k, v]) => ({ name: kebab(k), property: k, kind: v.kind, description: v.doc })),
  properties: Object.entries(c.props)
    .filter(([, v]) => v.kind === 'function')
    .map(([k, v]) => ({ name: k, description: v.doc })),
  events: Object.entries(c.props)
    .filter(([, v]) => v.kind === 'event')
    .map(([k, v]) => ({ name: eventName(k), prop: k, description: v.doc })),
  slots: Object.entries(c.props)
    .filter(([, v]) => v.kind === 'node')
    .map(([k, v]) => ({ name: k === 'children' ? '(default)' : kebab(k), prop: k, description: v.doc })),
}));
writeFileSync(resolve(root, 'src/elements/manifest.generated.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`elements: ${components.length} custom elements (${relative(root, resolve(root, 'src/elements/registry.generated.ts'))})`);
